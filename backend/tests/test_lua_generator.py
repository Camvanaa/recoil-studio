from app.models.schemas import GunConfig, RecoilData, SensitivitySettings
from app.services.lua_generator import LuaGenerator


def test_generate_lua_includes_gun_config_and_sensitivity_values():
    gun = GunConfig(
        name="M14",
        rpm=700,
        vertical_mul=1.2,
        horizontal_mul=0.8,
        scope_zoom=2.0,
        hold_breath_coeff=0.75,
        pattern=[RecoilData(y=10.5, x=-1.25), RecoilData(y=12, x=0)],
    )
    sensitivity = SensitivitySettings(
        mouse_sens=4.5,
        vertical_sens=1.1,
        horizontal_sens=0.9,
        ads_sens_mul=0.8,
        ads_vertical_sens=1.2,
        ads_horizontal_sens=1.3,
        screen_dist_coeff=1.0,
        base_fov=95,
        hold_breath=True,
    )

    lua_code = LuaGenerator.generate([gun], sensitivity)

    assert "Generated by Recoil Studio" in lua_code
    assert 'name = "M14"' in lua_code
    assert "rpm = 700" in lua_code
    assert "verticalMul = 1.2" in lua_code
    assert "horizontalMul = 0.8" in lua_code
    assert "scopeZoom = 2.0" in lua_code
    assert "holdBreathCoeff = 0.75" in lua_code
    assert 'fireMode = "auto"' in lua_code
    assert "{y=10.5, x=-1.25}" in lua_code
    assert "{y=12.0, x=0.0}" in lua_code
    assert "local mouseSens = 4.5" in lua_code
    assert "local holdBreath = true" in lua_code


def test_generate_lua_uses_default_sensitivity_when_omitted():
    gun = GunConfig(name="AK", pattern=[RecoilData(y=1, x=2)])

    lua_code = LuaGenerator.generate([gun])

    assert "local mouseSens = 5" in lua_code
    assert "local holdBreath = false" in lua_code
    assert 'name = "AK"' in lua_code


def test_generate_lua_includes_tap_fire_mode():
    gun = GunConfig(name="M14", fire_mode="tap", pattern=[RecoilData(y=1, x=2)])

    lua_code = LuaGenerator.generate([gun])

    assert 'fireMode = "tap"' in lua_code
    assert "function tapFireButton()" in lua_code
    assert "function sleepWhileButtonHeld(duration, holdBtn)" in lua_code
    assert "function resetRecoilCounters()" in lua_code
    assert "function isSyntheticTapEvent()" not in lua_code
    assert "function getTriggerButton(gun)" not in lua_code
    assert "return tapTriggerBtn" not in lua_code
    assert "tapFireButton()" in lua_code
    assert "if not tapFireButton() then" in lua_code
    assert "PressAndReleaseMouseButton(clickBtn)" not in lua_code
    assert "ReleaseMouseButton(clickBtn)" in lua_code
    assert "PressMouseButton(clickBtn)" in lua_code
    assert "EnablePrimaryMouseButtonEvents(false)" not in lua_code
    assert "local recoilRunning = false" in lua_code
    assert "local tapTriggerBtn = 4" not in lua_code
    assert "local tapQuickSwitchEnabled = false" in lua_code
    assert "tapSyntheticReleaseEvents" not in lua_code
    assert "tapSyntheticPressEvents" not in lua_code
    assert "and isSyntheticTapEvent()" not in lua_code
    assert "arg == clickBtn and recoilEnabled and not recoilRunning" in lua_code
    assert "while currentBullet < #gun.pattern and IsMouseButtonPressed(clickBtn) do" in lua_code
    assert "if not sleepWhileButtonHeld(sleepTime, clickBtn) then" in lua_code
    assert 'local tapQuickKeyA = "3"' in lua_code
    assert 'local tapQuickKeyB = "1"' in lua_code
    assert "local tapQuickDelay = 1" in lua_code
    assert "PressKey(tapQuickKeyA)" in lua_code
    assert "PressKey(tapQuickKeyB)" in lua_code
